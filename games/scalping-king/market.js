  function randomGenerator(seed) {
    return function () {
      seed = (seed + 0x6d2b79f5) >>> 0;
      let mixed = Math.imul(seed ^ (seed >>> 15), seed | 1);
      mixed ^= mixed + Math.imul(mixed ^ (mixed >>> 7), mixed | 61);
      return ((mixed ^ (mixed >>> 14)) >>> 0) / 4294967296;
    };
  }

  function integer(random, min, max) {
    return min + Math.floor(random() * (max - min + 1));
  }

  function priceStep(price) {
    return Math.max(PRICE_STEP, Math.round(price / PRICE_STEP) * PRICE_STEP);
  }

  function barsFromHistory(random, reference) {
    const closes = Array(25).fill(reference);
    for (let i = 23; i >= 0; i--) {
      closes[i] = priceStep(closes[i + 1] * (1 + (random() - .5) * .034));
    }
    return closes.slice(1).map((close, index) => ({
      time: (index - 24) * 60,
      open: closes[index], close,
      high: priceStep(Math.max(close, closes[index]) * (1 + random() * .009)),
      low: priceStep(Math.min(close, closes[index]) * (1 - random() * .009)),
      volume: integer(random, 17000, 73000),
    }));
  }

  function initialTicks(random, bars) {
    return bars.flatMap((bar) => {
      let previous = bar.open;
      return Array.from({length: 40}, (_, index) => {
        const close = index === 39 ? bar.close : Math.max(bar.low, Math.min(bar.high,
          priceStep(bar.open + (bar.close - bar.open) * (index + 1) / 40 + (random() - .5) * bar.open * .005)));
        const point = {time: bar.time + index * 1.5, open: previous, close,
          high: Math.max(previous, close), low: Math.min(previous, close), volume: integer(random, 95, 840)};
        previous = close;
        return point;
      });
    });
  }

  function fillHistoricalTicks(anchors) {
    return anchors.flatMap(anchor => {
      let open = anchor.open;
      return Array.from({length: 3}, (_, index) => {
        const close = priceStep(anchor.open + (anchor.close - anchor.open) * (index + 1) / 3);
        const volume = Math.floor(anchor.volume * (index + 1) / 3) - Math.floor(anchor.volume * index / 3);
        const tick = {time: anchor.time + (index + 1) / 2, open, close,
          high: Math.max(open, close), low: Math.min(open, close), volume};
        open = close;
        return tick;
      });
    });
  }

  function updateSeries(series, point) {
    const timeMs = Math.round(point.time * 1000) - 1;
    for (const period of CHART_PERIODS) {
      const bars = series[period];
      const time = Math.floor(timeMs / (period * 1000)) * period;
      const last = bars.at(-1);
      if (last?.time === time) {
        if (!point.volume) continue;
        if (!last.volume) Object.assign(last, point, {time, volume: 0});
        last.high = Math.max(last.high, point.high);
        last.low = Math.min(last.low, point.low);
        last.close = point.close;
        last.volume += point.volume;
      } else {
        bars.push({...point, time});
        if (bars.length > 100) bars.shift();
      }
    }
  }

  function eventSchedule(random, stocks) {
    const windows = Array.from({length: 5}, () => []);
    for (const stock of stocks) {
      const count = integer(random, 1, windows.length);
      const remainingWindows = windows.slice();
      const {good, bad} = STOCKS[stock.sourceIndex].at(-1);
      const positive = good.slice();
      const negative = bad.slice();
      for (let i = 0; i < count; i++) {
        const [window] = remainingWindows.splice(integer(random, 0, remainingWindows.length - 1), 1);
        const direction = !negative.length || (positive.length && random() < .5) ? 1 : -1;
        const pool = direction > 0 ? positive : negative;
        const [title] = pool.splice(integer(random, 0, pool.length - 1), 1);
        const strength = .0015 + random() * .0033;
        window.push({index: stock.index, direction, title, strength, duration: integer(random, 20, 34)});
      }
    }
    const windowSize = TOTAL_TICKS / windows.length;
    return windows.flatMap((window, index) => window.map((_, position) => {
      const pick = integer(random, position, window.length - 1);
      [window[position], window[pick]] = [window[pick], window[position]];
      return {...window[position], tick: 10 + index * windowSize + position * 11 + integer(random, 0, 7)};
    }));
  }

  function createMarket(seed, liveSeed) {
    const random = randomGenerator(seed);
    const bookRandom = randomGenerator(seed ^ 0x6ab02ed9);
    const historyRandom = randomGenerator(seed ^ 0x3c7fd5a5);
    const rosterRandom = randomGenerator(seed ^ 0x1c86470b);
    const roster = STOCKS.map((_, index) => index);
    for (let i = 0; i < WATCHLIST_SIZE; i++) {
      const pick = integer(rosterRandom, i, roster.length - 1);
      [roster[i], roster[pick]] = [roster[pick], roster[i]];
    }
    const market = {seed, time: 0, tick: 0, notices: [], eventIndex: 0};
    const stocks = roster.slice(0, WATCHLIST_SIZE).map((sourceIndex, index) => {
      const [name, sector, short, color, description, volatility, {opening}] = STOCKS[sourceIndex];
      const [openingDirection, preview] = opening[integer(rosterRandom, 0, opening.length - 1)];
      const reference = integer(random, 200, 1000) * PRICE_STEP;
      const bars = barsFromHistory(random, reference);
      const earlier = initialTicks(historyRandom, bars.slice(-10, -2));
      const recent = initialTicks(random, bars.slice(-2));
      const history = fillHistoricalTicks(earlier.concat(recent));
      const series = Object.fromEntries(CHART_PERIODS.map(period => [period, []]));
      history.forEach(point => updateSeries(series, point));
      const stock = {index, sourceIndex, name, sector, short, color, description, preview, openingDirection, volatility,
        reference, series, ticks: history.slice(-180), price: reference, volume: 0,
        high: reference, low: reference, shock: 0, shockTicks: 0};
      engine.initialize(stock, market, bookRandom, fill => {
        const point = {time: fill.time || .001, open: fill.price, close: fill.price,
          high: fill.price, low: fill.price, volume: fill.qty};
        updateSeries(stock.series, point);
        if (stock.currentPoint) {
          if (!stock.currentPoint.volume) Object.assign(stock.currentPoint, point, {time: stock.currentPoint.time, volume: 0});
          stock.currentPoint.high = Math.max(stock.currentPoint.high, point.high);
          stock.currentPoint.low = Math.min(stock.currentPoint.low, point.low);
          stock.currentPoint.close = fill.price;
          stock.currentPoint.volume += fill.qty;
        }
      });
      return stock;
    });
    const headlines = stocks.map(stock => ({index: stock.index, title: stock.preview, time: 0, direction: stock.openingDirection}));
    const scheduleRandom = liveSeed === undefined ? random : randomGenerator(liveSeed);
    const disclosureRandom = randomGenerator((liveSeed ?? seed) ^ 0x96f89e43);
    const disclosures = disclosureSchedule(disclosureRandom, stocks);
    if (disclosureRandom() < .55) {
      const index = integer(disclosureRandom, 0, stocks.length - 1);
      const direction = disclosureRandom() < .5 ? -1 : 1;
      disclosures.push({index, direction, tick: integer(disclosureRandom, 60, 365),
        title: direction > 0 ? "대량 매수 주문에 추격매수가 유입되고 있어요." : "대량 매도에 차익실현과 손절 주문이 몰리고 있어요.",
        strength: 0, duration: 0, flowDuration: integer(disclosureRandom, 82, 113)});
    }
    return Object.assign(market, {stocks, headlines, random: bookRandom,
      events: eventSchedule(scheduleRandom, stocks).concat(disclosures).sort((a, b) => a.tick - b.tick)});
  }


