'use strict';
const assert = require('node:assert/strict');
const {createSign, generateKeyPairSync} = require('node:crypto');
const fs = require('node:fs');
const {join} = require('node:path');
for (const file of ['risk-v2', 'microstructure-v2', 'ledger-v2', 'engine-v2', 'market']) require('./' + file + '.js');

async function main() {
  const {commandFrom, elapsedMs, finalScore, replay, tickAt, FULL_MS} = await import('./official-engine.mjs');
  const {verifyAdMob} = await import('../../supabase/functions/scalping-king/verify-admob.mjs');
  const {marketFeed} = await import('../../supabase/functions/scalping-king/market-feed.mjs');
  const seed = 71;
  assert.equal(commandFrom({kind: 'order', stock: 0, side: 'buy', qty: 2, price: null, tick: 599}).tick, undefined);
  assert.equal(commandFrom({kind: 'order', stock: 0, side: 'buy', qty: 1e12}), null);
  assert.equal(commandFrom({kind: 'credit', stock: 0, percent: 310}), null);
  assert.throws(() => replay(seed, [{kind: 'emergency', tick: 0}], 0), /cannot be replayed/);
  const privateRound = {session_id: 'a', server_seed: seed, market_key: 'hidden-per-round-key'};
  const feed1 = marketFeed(privateRound, 32);
  const feed2 = marketFeed(privateRound, 64, 32);
  assert.equal(feed1.seeds.length, 32);
  assert.equal(feed2.seeds.length, 32);
  assert.ok(feed1.events.every(event => event.tick <= 32));
  assert.ok(feed2.events.every(event => event.tick > 32 && event.tick <= 64));
  assert.deepEqual([...feed1.seeds, ...feed2.seeds], marketFeed(privateRound, 64).seeds);
  assert.throws(() => replay(seed, [], 33, feed1), /Missing official market tick/);
  assert.notDeepEqual(feed1.seeds, marketFeed({...privateRound, session_id: 'b', market_key: 'other-hidden-key'}, 32).seeds);
  const trail = [{kind: 'order', stock: 0, side: 'buy', qty: 2, price: null, tick: 0}];
  assert.equal(replay(seed, trail, 0).account.positions[0].qty, 2);
  const score = finalScore(replay(seed, trail, tickAt(FULL_MS)));
  assert.equal(score, finalScore(replay(seed, trail, tickAt(FULL_MS))));
  assert.notEqual(score, 100000000);
  assert.throws(() => replay(seed, [{...trail[0], tick: 33}, trail[0]], 40), /Invalid stored command tick/);
  const anchor = '2026-11-12T00:00:00.000Z';
  assert.equal(elapsedMs({anchor_at: anchor, server_ms: Date.parse(anchor) + 2000, elapsed_ms: 5, paused: true}), 5);
  assert.equal(elapsedMs({anchor_at: anchor, server_ms: Date.parse(anchor) + 2000, elapsed_ms: 5, paused: false}), 2005);

  const {privateKey, publicKey} = generateKeyPairSync('ec', {namedCurve: 'prime256v1'});
  const query = 'ad_unit=123&custom_data=some%2Dnonce&timestamp=1794442000123&transaction_id=1234567890abcdef';
  const signature = createSign('SHA256').update(query).sign(privateKey).toString('base64url');
  const url = 'https://example.com/ssv?' + query + '&signature=' + signature + '&key_id=7';
  const keys = async () => [{keyId: 7, pem: publicKey.export({type: 'spki', format: 'pem'})}];
  assert.equal((await verifyAdMob(url, {credit: '123'}, keys)).nonce, 'some-nonce');
  assert.equal(await verifyAdMob(url.replace('1234567890abcdef', '1234567890abcdee'), {credit: '123'}, keys), null);
  assert.equal(await verifyAdMob(url, {extra: '456'}, keys), null);
  assert.equal(await verifyAdMob(url + '&timestamp=1794442000123', {credit: '123'}, keys), null);

  const {PGlite} = require(process.env.PGLITE_PATH || '@electric-sql/pglite');
  const db = new PGlite();
  try {
    await db.exec('create schema auth; create table auth.users (id uuid primary key); create role anon; create role authenticated; create role service_role bypassrls;');
    const migrations = join(__dirname, '../../supabase/migrations');
    const migration = fs.readdirSync(migrations).find(file => file.endsWith('_scalping_king_official.sql'));
    await db.exec(fs.readFileSync(join(migrations, migration), 'utf8'));
    const p = 'c1797faa-c30d-4603-ad43-59053f0429ec';
    const q = 'c1797faa-c30d-4603-ad43-59053f0429ee';
    await db.query('insert into auth.users values ($1), ($2)', [p, q]);
    const value = async (sql, args) => (await db.query(sql, args)).rows[0]?.v;
    const profile = (user, nick) => value('select public.scalping_profile($1,$2) v', [user, nick ?? null]);
    const start = (user, id, restart) => value('select public.scalping_start($1,$2,$3,$4,$5) v', [user, id, '20261112.1', 71, restart]);
    const id = n => '00000000-0000-4000-8000-' + String(n).padStart(12, '0');
    assert.equal((await start(p,id(1),false)).error, 'nickname_required');
    assert.equal((await profile(p,'테스터')).free, 5);
    assert.equal((await profile(q,'Tester')).nickname, 'Tester');
    await assert.rejects(profile(p,'tester'), /duplicate key/i);
    const initial = await start(p,id(1),false);
    assert.equal((await start(p,id(1),true)).session_id, initial.session_id);
    assert.equal((await start(p,id(2),false)).session_id, initial.session_id);
    assert.equal((await profile(p)).free, 4);
    for (let round = 2; round <= 5; round++) assert.ok((await start(p,id(round),true)).session_id);
    assert.equal((await start(p,id(6),true)).error, 'quota_exhausted');
    assert.equal((await profile(p)).free, 0);
    const nonce = await value("select public.scalping_ad_intent($1,null,'extra') v",[p]);
    assert.ok(nonce);
    const verify = (feature, transaction) => value('select public.scalping_verify_ad($1,$2,$3,now()) v',[nonce,feature,transaction]);
    assert.equal(await verify('credit','0123456789abcdef'),false);
    assert.equal(await verify('extra','0123456789abcdef'),true);
    assert.equal(await verify('extra','0123456789abcdef'),true);
    assert.equal((await profile(p)).bonus,1);
    const extra = await start(p,id(6),true);
    assert.ok(extra.session_id);
    assert.equal((await profile(p)).bonus,0);
    assert.equal((await start(p,id(7),true)).error,'quota_exhausted');
    assert.equal(await value('select public.scalping_session($1,$2) v',[q, extra.session_id]),null);
    assert.equal(await value('select public.scalping_commit($1,$2,0,null,300000,false,clock_timestamp(),$3) v',[p,extra.session_id,score]),true);
    assert.equal(await value('select public.scalping_commit($1,$2,0,null,300000,false,clock_timestamp(),$3) v',[p,extra.session_id,score+1]),false);
    const next = await start(q,id(8),true);
    assert.equal(await value('select public.scalping_commit($1,$2,0,null,300000,false,clock_timestamp(),$3) v',[q,next.session_id,score]),true);
    const ranking = await value('select public.scalping_rankings() v');
    assert.deepEqual(ranking.profits.map(row=>row.nickname),['테스터','Tester']);
    assert.deepEqual(ranking.rates.map(row=>row.nickname),['테스터','Tester']);
    assert.ok(!JSON.stringify(ranking).includes(p));
    await db.exec('set role authenticated');
    await assert.rejects(value('select public.scalping_rankings() v'),/permission denied/i);
    await assert.rejects(db.exec('update scalping_private.verified_scores set final_equity=5'),/permission denied/i);
    await db.exec('reset role');
    await db.query("update scalping_private.game_sessions set kst_day=(now() at time zone 'Asia/Seoul')::date - 3 where session_id=$1",[initial.session_id]);
    const clean = await value("select public.scalping_maintenance('cleanup') v");
    assert.equal(clean.ok,true);
    assert.equal(clean.deleted,1);
    assert.ok((await profile(p)).nickname);
    assert.equal((await value("select public.scalping_maintenance('keepalive') v")).ok,true);
  } finally { await db.close(); }
  console.log('Server replay, signed AdMob callback, PostgreSQL quotas, permissions, ranking and retention tests passed');
}

main().catch(error => {console.error(error); process.exitCode=1;});
